import type { ComarkElementAttributes, ComarkNode, ComarkPlugin } from 'comark'

/**
 * Positive allowlist for markdown produced by the model.
 *
 * Comark renders any tag it finds, resolving it to globally registered components
 * (Nuxt UI registers dozens of `Prose*` components, some of them with links) and it honours
 * an `as` prop to swap the component. The `security` plugin only validates `href`/`src`,
 * so this plugin runs last and keeps only plain markdown elements with known props.
 * Unknown elements are unwrapped: their children stay, the element itself is dropped.
 */

const ALLOWED_TAGS = new Set([
  'p',
  'br',
  'hr',
  'strong',
  'em',
  'del',
  's',
  'a',
  'code',
  'pre',
  'span',
  'ul',
  'ol',
  'li',
  'blockquote',
  'h1',
  'h2',
  'h3',
  'h4',
  'h5',
  'h6',
  'table',
  'thead',
  'tbody',
  'tr',
  'th',
  'td',
  'source-link',
])

/** Inside a code block only the nodes generated by the highlighter are kept */
const PRE_CHILD_TAGS = new Set(['code', 'span'])

const PRE_CLASS_TOKEN = /^(?:shiki(?:-themes)?|material-theme(?:-[a-z]+)*)$/
const CODE_CLASS_TOKEN = /^language-[\w-]+$/
const SPAN_CLASS_TOKENS = new Set(['line', 'highlight'])
/** Inline styles emitted by shiki: colors, CSS variables and `display` */
const CODE_STYLE =
  /^(?:\s*(?:color|background-color|display|font-style|font-weight|text-decoration|--shiki-[\w-]+)\s*:\s*[#\w\s(),.%-]+;?)*\s*$/
const TABLE_ALIGN_STYLE = /^\s*text-align\s*:\s*(?:left|center|right)\s*;?\s*$/
const TABLE_ALIGN = new Set(['left', 'center', 'right'])

function filterClass(value: unknown, allowed: (token: string) => boolean): string | undefined {
  if (typeof value !== 'string') return undefined

  const tokens = value.split(/\s+/).filter(token => token && allowed(token))
  return tokens.length > 0 ? tokens.join(' ') : undefined
}

function asString(value: unknown): string | undefined {
  return typeof value === 'string' ? value : undefined
}

function sanitizeProp(tag: string, name: string, value: unknown, insidePre: boolean): unknown {
  if (insidePre) {
    if (name === 'class') {
      return filterClass(value, token =>
        tag === 'code' ? CODE_CLASS_TOKEN.test(token) : SPAN_CLASS_TOKENS.has(token)
      )
    }
    if (name === 'style') {
      return typeof value === 'string' && CODE_STYLE.test(value) ? value : undefined
    }
    return undefined
  }

  switch (tag) {
    case 'a':
      return name === 'href' || name === 'title' ? asString(value) : undefined

    case 'ol':
      return name === 'start' && /^\d{1,6}$/.test(String(value)) ? value : undefined

    case 'th':
    case 'td':
      if (name === 'align') return TABLE_ALIGN.has(String(value)) ? value : undefined
      if (name === 'style')
        return typeof value === 'string' && TABLE_ALIGN_STYLE.test(value) ? value : undefined
      return undefined

    case 'pre':
      if (name === 'code' || name === 'language' || name === 'filename' || name === 'meta')
        return asString(value)
      if (name === 'highlights')
        return Array.isArray(value) && value.every(line => typeof line === 'number')
          ? value
          : undefined
      if (name === 'tabindex') return '0'
      if (name === 'class') return filterClass(value, token => PRE_CLASS_TOKEN.test(token))
      return undefined

    case 'source-link':
      return name === 'url' ? asString(value) : undefined

    default:
      return undefined
  }
}

function sanitizeAttributes(
  tag: string,
  attributes: ComarkElementAttributes | undefined,
  insidePre: boolean
): ComarkElementAttributes {
  const result: ComarkElementAttributes = {}
  if (!attributes) return result

  // Parser metadata (source line, block/inline), never rendered as an attribute
  if (attributes.$) result.$ = attributes.$

  for (const [rawName, value] of Object.entries(attributes)) {
    if (rawName === '$') continue

    const name = rawName === 'className' ? 'class' : rawName
    const sanitized = sanitizeProp(tag, name, value, insidePre)
    if (sanitized !== undefined) {
      result[name] = sanitized
    }
  }

  return result
}

/**
 * Sanitizes a list of Comark nodes. Exported for unit tests.
 */
export function sanitizeComarkNodes(nodes: readonly ComarkNode[], insidePre = false): ComarkNode[] {
  const result: ComarkNode[] = []

  for (const node of nodes) {
    if (typeof node === 'string') {
      result.push(node)
      continue
    }

    const [tag, attributes, ...children] = node

    // Comments (`[null, {}, text]`) are not rendered
    if (typeof tag !== 'string') continue

    const name = tag.toLowerCase()
    const allowed = insidePre ? PRE_CHILD_TAGS.has(name) : ALLOWED_TAGS.has(name)
    const safeChildren = sanitizeComarkNodes(children as ComarkNode[], insidePre || name === 'pre')

    if (!allowed) {
      result.push(...safeChildren)
      continue
    }

    result.push([name, sanitizeAttributes(name, attributes, insidePre), ...safeChildren])
  }

  return result
}

/**
 * Options for the comark `security` plugin when rendering model output.
 * Kept here (pure module, no aliases) so the renderer and the unit tests share them.
 */
export function chatSecurityOptions(siteUrl: string) {
  return {
    blockedTags: [
      'script',
      'style',
      'iframe',
      'frame',
      'frameset',
      'object',
      'embed',
      'form',
      'input',
      'button',
      'textarea',
      'select',
      'base',
      'meta',
      'link',
      'svg',
      'math',
      'img',
      'video',
      'audio',
      'source',
      'picture',
    ],
    allowedProtocols: ['https', 'mailto'],
    allowedImagePrefixes: [`${siteUrl.replace(/\/$/, '')}/`],
    allowDataImages: false,
  }
}

export function chatAllowlist(): ComarkPlugin {
  return {
    name: 'chat-allowlist',
    post(state) {
      state.tree = {
        ...state.tree,
        nodes: sanitizeComarkNodes(state.tree.nodes),
      }
    },
  }
}
